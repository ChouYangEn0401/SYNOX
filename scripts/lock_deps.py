"""Write requirements.lock: every runtime dependency of SYNOX pinned with ==, optionally with sha256 hashes.

    <python> scripts\\lock_deps.py                         pin from the packages installed in THIS interpreter
    <python> scripts\\lock_deps.py --wheelhouse wheelhouse   also add --hash=sha256:... for each wheel found there
    <python> scripts\\lock_deps.py --check                   exit 1 if requirements.lock is missing or stale

Run it on the release build machine, in a fresh venv where `pip install -e .` just succeeded (docs/adr/0003).
Never downloads anything: versions come from importlib.metadata, hashes from wheel files already on disk.
To fill a wheelhouse for an offline install (on the build machine, with network):

    <python> -m pip download -r requirements.lock -d wheelhouse --only-binary=:all:
    <python> -m pip download "setuptools>=64" -d wheelhouse      (needed to build SYNOX itself offline)

setup/bootstrap.ps1 uses wheelhouse/ (offline, --no-index) when it exists, else requirements.lock when it exists,
else plain `pip install -e .` (the pyproject ranges). Output is ASCII (pip reads it in the console code page).
"""

from __future__ import annotations

import argparse
import datetime
import hashlib
import importlib.metadata as md
import os
import platform
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
LOCK = os.path.join(ROOT, "requirements.lock")
NAME_RE = re.compile(r"^\s*([A-Za-z0-9][A-Za-z0-9._-]*)")


def canon(name: str) -> str:
    return re.sub(r"[-_.]+", "-", name).lower()


def top_level(pyproject: str = os.path.join(ROOT, "pyproject.toml")) -> list:
    """pyproject.toml [project].dependencies -> names (no extras: dev / llm are not runtime)."""
    import tomllib
    with open(pyproject, "rb") as f:
        deps = tomllib.load(f)["project"]["dependencies"]
    return [NAME_RE.match(d).group(1) for d in deps]


def _requires(dist) -> list:
    """Names this distribution needs at runtime (skips extras-only requirements; keeps platform markers' deps
    only when they are installed, see closure)."""
    out = []
    for req in dist.requires or []:
        if re.search(r"\bextra\s*==", req):
            continue
        m = NAME_RE.match(req)
        if m:
            out.append((m.group(1), ";" in req))
    return out


def closure(names, find=md.distribution) -> dict:
    """{canonical name: (project name, version)} for names and everything they need, from installed metadata.
    A dependency behind an environment marker that is not installed is skipped (it is for another platform);
    a missing unconditional one raises LookupError."""
    found: dict = {}
    todo = [(n, False) for n in names]
    while todo:
        name, optional = todo.pop()
        key = canon(name)
        if key in found:
            continue
        try:
            dist = find(name)
        except md.PackageNotFoundError:
            if optional:
                continue
            raise LookupError(f"{name} is not installed in this interpreter ({sys.executable}); "
                              "run `pip install -e .` in a fresh venv first")
        found[key] = (dist.metadata["Name"], dist.version)
        todo += _requires(dist)
    return found


def wheel_hashes(wheelhouse: str) -> dict:
    """{canonical name: {version: [sha256, ...]}} for every .whl in the folder (file names only, nothing is run)."""
    out: dict = {}
    if not wheelhouse or not os.path.isdir(wheelhouse):
        return out
    for fname in sorted(os.listdir(wheelhouse)):
        if not fname.endswith(".whl"):
            continue
        parts = fname[:-4].split("-")
        if len(parts) < 5:
            continue
        h = hashlib.sha256()
        with open(os.path.join(wheelhouse, fname), "rb") as f:
            for chunk in iter(lambda: f.read(65536), b""):
                h.update(chunk)
        out.setdefault(canon(parts[0]), {}).setdefault(parts[1], []).append(h.hexdigest())
    return out


def render(pins: dict, hashes: dict, today: str = "") -> str:
    lines = ["# requirements.lock -- generated by scripts/lock_deps.py; do not edit by hand (ASCII only).",
             f"# python {platform.python_version()} on {sys.platform}; {today or datetime.date.today().isoformat()}",
             "# Install: python -m pip install -r requirements.lock  then  python -m pip install --no-deps -e ."]
    for key in sorted(pins):
        name, version = pins[key]
        line = f"{name}=={version}"
        for digest in hashes.get(key, {}).get(version, []):
            line += f" \\\n    --hash=sha256:{digest}"
        lines.append(line)
    return "\n".join(lines) + "\n"


def stale(path: str = LOCK, names=None) -> list:
    """Problems with an existing lock: missing file, or a pyproject dependency that is not pinned."""
    if not os.path.isfile(path):
        return [f"{os.path.basename(path)} does not exist"]
    with open(path, "r", encoding="ascii") as f:
        text = f.read()
    pinned = {canon(m.group(1)) for m in re.finditer(r"^([A-Za-z0-9][A-Za-z0-9._-]*)==", text, re.M)}
    return [f"{n} is in pyproject.toml but not pinned" for n in (names or top_level()) if canon(n) not in pinned]


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--out", default=LOCK)
    parser.add_argument("--wheelhouse", default="", help="folder of downloaded wheels: add their sha256 hashes")
    parser.add_argument("--check", action="store_true", help="only check that the lock exists and covers pyproject")
    args = parser.parse_args(argv)
    if args.check:
        problems = stale(args.out)
        for p in problems:
            print(f"[X] {p}")
        return 1 if problems else 0
    try:
        pins = closure(top_level())
    except LookupError as e:
        print(f"[X] {e}")
        return 1
    text = render(pins, wheel_hashes(args.wheelhouse))
    text.encode("ascii")
    with open(args.out, "w", encoding="ascii", newline="\n") as f:
        f.write(text)
    print(f"{args.out}  ({len(pins)} packages)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
